# Bakes Silkscreen (a pixel font, OFL) into common/font.h: 6x8 cells for
# ASCII 32..126, one byte per row, bit 7 = leftmost pixel.
import os
from PIL import Image, ImageDraw, ImageFont
here = os.path.dirname(os.path.abspath(__file__))
font = ImageFont.truetype(os.path.join(here, 'Silkscreen-400.ttf'), 8)
def glyph(c):
    im = Image.new('1', (14, 14), 0)
    ImageDraw.Draw(im).text((2, 0), chr(c), font=font, fill=1)
    return im
# One top line for all, so letters share a baseline; each glyph starts at its
# own left edge.
top = min(glyph(c).getbbox()[1] for c in range(33, 127))
rows, widths = [], []
for c in range(32, 127):
    im = glyph(c)
    box = im.getbbox()
    left = box[0] if box else 0
    widths.append(min(box[2] - box[0] + 1, 7) if box else 3)
    for y in range(8):
        b = 0
        for x in range(7):
            if left + x < 14 and top + y < 14 and im.getpixel((left + x, top + y)): b |= 0x80 >> x
        rows.append(b)
with open(os.path.join(here, '..', 'common', 'font.h'), 'w') as f:
    f.write('// Generated by tools/makefont.py from Silkscreen (SIL Open Font License).\n')
    f.write('static const unsigned char font_rows[95 * 8] = {\n')
    for i in range(0, len(rows), 16): f.write('    ' + ', '.join('0x%02X' % r for r in rows[i:i + 16]) + ',\n')
    f.write('};\nstatic const unsigned char font_widths[95] = {\n')
    for i in range(0, 95, 24): f.write('    ' + ', '.join(str(w) for w in widths[i:i + 24]) + ',\n')
    f.write('};\n')
